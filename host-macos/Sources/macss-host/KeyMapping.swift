import CoreGraphics

/// Maps USB HID usage ids (usage page 0x07) to macOS virtual key codes.
///
/// The client reports HID usage ids so the same event means the same physical
/// key on Windows and macOS. This table covers the ANSI layout plus modifiers,
/// function keys, navigation cluster and the numeric keypad.
enum KeyMapping {
    static func keyCode(forHID hid: UInt16) -> CGKeyCode? {
        table[hid]
    }

    private static let table: [UInt16: CGKeyCode] = [
        // Letters
        0x04: 0x00, 0x05: 0x0B, 0x06: 0x08, 0x07: 0x02, 0x08: 0x0E, 0x09: 0x03,
        0x0A: 0x05, 0x0B: 0x04, 0x0C: 0x22, 0x0D: 0x26, 0x0E: 0x28, 0x0F: 0x25,
        0x10: 0x2E, 0x11: 0x2D, 0x12: 0x1F, 0x13: 0x23, 0x14: 0x0C, 0x15: 0x0F,
        0x16: 0x01, 0x17: 0x11, 0x18: 0x20, 0x19: 0x09, 0x1A: 0x0D, 0x1B: 0x07,
        0x1C: 0x10, 0x1D: 0x06,
        // Digits
        0x1E: 0x12, 0x1F: 0x13, 0x20: 0x14, 0x21: 0x15, 0x22: 0x17, 0x23: 0x16,
        0x24: 0x1A, 0x25: 0x1C, 0x26: 0x19, 0x27: 0x1D,
        // Punctuation and whitespace
        0x28: 0x24, // Return
        0x29: 0x35, // Escape
        0x2A: 0x33, // Backspace
        0x2B: 0x30, // Tab
        0x2C: 0x31, // Space
        0x2D: 0x1B, // -
        0x2E: 0x18, // =
        0x2F: 0x21, // [
        0x30: 0x1E, // ]
        0x31: 0x2A, // backslash
        0x33: 0x29, // ;
        0x34: 0x27, // '
        0x35: 0x32, // `
        0x36: 0x2B, // ,
        0x37: 0x2F, // .
        0x38: 0x2C, // /
        0x39: 0x39, // Caps Lock
        // Function row
        0x3A: 0x7A, 0x3B: 0x78, 0x3C: 0x63, 0x3D: 0x76, 0x3E: 0x60, 0x3F: 0x61,
        0x40: 0x62, 0x41: 0x64, 0x42: 0x65, 0x43: 0x6D, 0x44: 0x67, 0x45: 0x6F,
        // Navigation
        0x49: 0x72, // Insert -> Help
        0x4A: 0x73, // Home
        0x4B: 0x74, // Page Up
        0x4C: 0x75, // Delete -> Forward Delete
        0x4D: 0x77, // End
        0x4E: 0x79, // Page Down
        0x4F: 0x7C, // Right
        0x50: 0x7B, // Left
        0x51: 0x7D, // Down
        0x52: 0x7E, // Up
        // Keypad
        0x53: 0x47, // Num Lock -> Clear
        0x54: 0x4B, // /
        0x55: 0x43, // *
        0x56: 0x4E, // -
        0x57: 0x45, // +
        0x58: 0x4C, // Enter
        0x59: 0x53, 0x5A: 0x54, 0x5B: 0x55, 0x5C: 0x56, 0x5D: 0x57,
        0x5E: 0x58, 0x5F: 0x59, 0x60: 0x5B, 0x61: 0x5C, 0x62: 0x52,
        0x63: 0x41, // .
        // Modifiers
        0xE0: 0x3B, // Left Control
        0xE1: 0x38, // Left Shift
        0xE2: 0x3A, // Left Option
        0xE3: 0x37, // Left Command
        0xE4: 0x3E, // Right Control
        0xE5: 0x3C, // Right Shift
        0xE6: 0x3D, // Right Option
        0xE7: 0x36, // Right Command
    ]
}
